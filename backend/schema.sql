CREATE EXTENSION IF NOT EXISTS pgcrypto;

CREATE TABLE IF NOT EXISTS contacts (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  type TEXT NOT NULL CHECK (type IN ('vendor', 'customer')),
  full_name TEXT NOT NULL,
  phone TEXT NOT NULL DEFAULT '',
  email TEXT NOT NULL UNIQUE,
  company_name TEXT NOT NULL DEFAULT '',
  location TEXT NOT NULL DEFAULT '',
  address TEXT NOT NULL DEFAULT '',
  area TEXT NOT NULL DEFAULT '',
  tax_rate NUMERIC NOT NULL DEFAULT 0,
  cnic_front_url TEXT NOT NULL DEFAULT '',
  cnic_back_url TEXT NOT NULL DEFAULT '',
  cheque_url TEXT NOT NULL DEFAULT '',
  cnic_front_data TEXT NOT NULL DEFAULT '',
  cnic_back_data TEXT NOT NULL DEFAULT '',
  cheque_data TEXT NOT NULL DEFAULT '',
  temp_password TEXT NOT NULL DEFAULT '',
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

ALTER TABLE contacts ADD COLUMN IF NOT EXISTS cnic_front_data TEXT NOT NULL DEFAULT '';
ALTER TABLE contacts ADD COLUMN IF NOT EXISTS cnic_back_data TEXT NOT NULL DEFAULT '';
ALTER TABLE contacts ADD COLUMN IF NOT EXISTS cheque_data TEXT NOT NULL DEFAULT '';

CREATE TABLE IF NOT EXISTS users (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  email TEXT NOT NULL UNIQUE,
  password_hash TEXT NOT NULL,
  role TEXT NOT NULL CHECK (role IN ('admin', 'vendor', 'customer')),
  contact_id UUID REFERENCES contacts(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS sessions (
  token_hash TEXT PRIMARY KEY,
  user_id UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  expires_at TIMESTAMPTZ NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS invoices (
  id TEXT PRIMARY KEY,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  date TEXT NOT NULL,
  customer_name TEXT NOT NULL,
  customer_email TEXT NOT NULL DEFAULT '',
  customer_phone TEXT NOT NULL DEFAULT '',
  customer_id TEXT NOT NULL DEFAULT '',
  total_amount NUMERIC NOT NULL DEFAULT 0,
  tax_rate NUMERIC NOT NULL DEFAULT 0,
  tax_amount NUMERIC NOT NULL DEFAULT 0,
  baraf NUMERIC NOT NULL DEFAULT 0,
  rickshaw_rent NUMERIC NOT NULL DEFAULT 0,
  worker_expense NUMERIC NOT NULL DEFAULT 0,
  expense_total NUMERIC NOT NULL DEFAULT 0,
  amount_paid NUMERIC NOT NULL DEFAULT 0,
  payment_date TEXT NOT NULL DEFAULT '',
  balance NUMERIC NOT NULL DEFAULT 0,
  status TEXT NOT NULL DEFAULT 'Pending',
  notes TEXT NOT NULL DEFAULT '',
  items JSONB NOT NULL DEFAULT '[]'::jsonb,
  payments JSONB NOT NULL DEFAULT '[]'::jsonb,
  invoice_type TEXT NOT NULL DEFAULT 'customer'
);

CREATE TABLE IF NOT EXISTS vendor_invoices (LIKE invoices INCLUDING ALL);
ALTER TABLE vendor_invoices ALTER COLUMN invoice_type SET DEFAULT 'vendor';

CREATE TABLE IF NOT EXISTS user_settings (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id UUID REFERENCES users(id) ON DELETE CASCADE,
  user_email TEXT NOT NULL DEFAULT '',
  google_access_token TEXT NOT NULL DEFAULT '',
  google_refresh_token TEXT NOT NULL DEFAULT '',
  spreadsheet_settings JSONB DEFAULT '{}'::jsonb,
  invoice_template JSONB DEFAULT '{}'::jsonb,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE UNIQUE INDEX IF NOT EXISTS user_settings_user_id_key ON user_settings(user_id) WHERE user_id IS NOT NULL;

CREATE TABLE IF NOT EXISTS ledger_invoices (
  id TEXT PRIMARY KEY,
  guest_name TEXT NOT NULL,
  hotel_name TEXT NOT NULL,
  total_amount NUMERIC NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS cash_expenses (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  amount NUMERIC NOT NULL DEFAULT 0,
  description TEXT NOT NULL DEFAULT '',
  tag TEXT NOT NULL DEFAULT 'expense',
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS payment_logs (
  payment_id TEXT PRIMARY KEY,
  contact_id TEXT NOT NULL DEFAULT '',
  contact_name TEXT NOT NULL DEFAULT '',
  contact_phone TEXT NOT NULL DEFAULT '',
  amount NUMERIC NOT NULL DEFAULT 0,
  payment_date TEXT NOT NULL DEFAULT '',
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS payment_logs_created_at_idx ON payment_logs(created_at DESC);
CREATE INDEX IF NOT EXISTS payment_logs_contact_id_idx ON payment_logs(contact_id);

CREATE TABLE IF NOT EXISTS payment_entries (
  entry_key TEXT PRIMARY KEY,
  invoice_id TEXT NOT NULL,
  invoice_type TEXT NOT NULL CHECK (invoice_type IN ('customer', 'vendor')),
  contact_id TEXT NOT NULL DEFAULT '',
  contact_name TEXT NOT NULL DEFAULT '',
  contact_phone TEXT NOT NULL DEFAULT '',
  payment_id TEXT NOT NULL DEFAULT '',
  amount NUMERIC NOT NULL DEFAULT 0,
  applied_amount NUMERIC NOT NULL DEFAULT 0,
  payment_date TEXT NOT NULL DEFAULT '',
  entry_index INTEGER NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS payment_entries_invoice_idx ON payment_entries(invoice_id, invoice_type);
CREATE INDEX IF NOT EXISTS payment_entries_date_idx ON payment_entries(payment_date);
CREATE INDEX IF NOT EXISTS payment_entries_type_date_idx ON payment_entries(invoice_type, payment_date, applied_amount);
CREATE INDEX IF NOT EXISTS payment_entries_contact_date_idx ON payment_entries(contact_id, payment_date);

INSERT INTO payment_entries(entry_key, invoice_id, invoice_type, contact_id, contact_name, contact_phone, payment_id, amount, applied_amount, payment_date, entry_index)
SELECT
  source.invoice_type || ':' || source.id || ':' || COALESCE(NULLIF(payment.value->>'paymentId', ''), 'legacy') || ':' || (payment.ordinality - 1),
  source.id,
  source.invoice_type,
  source.customer_id,
  source.customer_name,
  source.customer_phone,
  COALESCE(payment.value->>'paymentId', ''),
  COALESCE(NULLIF(payment.value->>'amount', '')::numeric, 0),
  COALESCE(NULLIF(payment.value->>'appliedAmount', '')::numeric, NULLIF(payment.value->>'amount', '')::numeric, 0),
  COALESCE(payment.value->>'date', ''),
  payment.ordinality - 1
FROM (
  SELECT id, customer_id, customer_name, customer_phone, payments, 'customer' AS invoice_type FROM invoices
  UNION ALL
  SELECT id, customer_id, customer_name, customer_phone, payments, 'vendor' AS invoice_type FROM vendor_invoices
) source
CROSS JOIN LATERAL jsonb_array_elements(
  CASE WHEN jsonb_typeof(source.payments) = 'array' THEN source.payments ELSE '[]'::jsonb END
) WITH ORDINALITY payment
WHERE COALESCE(NULLIF(payment.value->>'amount', '')::numeric, 0) > 0
ON CONFLICT(entry_key) DO NOTHING;

INSERT INTO payment_logs(payment_id, contact_id, contact_name, contact_phone, amount, payment_date)
SELECT
  COALESCE(NULLIF(payment->>'paymentId', ''), source.id || '-' || COALESCE(NULLIF(payment->>'date', ''), 'payment')),
  source.customer_id,
  COALESCE(NULLIF(payment->>'contactName', ''), source.customer_name),
  COALESCE(NULLIF(payment->>'contactPhone', ''), source.customer_phone),
  SUM(COALESCE(NULLIF(payment->>'amount', '')::numeric, 0)),
  COALESCE(payment->>'date', '')
FROM (
  SELECT id, customer_id, customer_name, customer_phone, payments FROM invoices
  UNION ALL
  SELECT id, customer_id, customer_name, customer_phone, payments FROM vendor_invoices
) source
CROSS JOIN LATERAL jsonb_array_elements(
  CASE WHEN jsonb_typeof(source.payments) = 'array' THEN source.payments ELSE '[]'::jsonb END
) payment
WHERE COALESCE(NULLIF(payment->>'amount', '')::numeric, 0) > 0
GROUP BY 1, 2, 3, 4, 6
ON CONFLICT(payment_id) DO NOTHING;

